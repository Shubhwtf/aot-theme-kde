function M.load()
  if vim.g.colors_name then
    vim.cmd("hi clear")
  end
  vim.o.termguicolors = true
  vim.o.background = "dark"
  vim.g.colors_name = "attack-on-titan"
  local c = M.palette
  for name, spec in pairs(groups(c, M.config)) do
    vim.api.nvim_set_hl(0, name, spec)
  end
  local term = { c.bg1, c.crimson, c.green, c.brass, c.blue, "#9c5a7a", "#4f9a94", c.linen,
                 c.stone, c.red, c.moss, c.gold, c.sky, c.rose, c.teal, c.fg_hi }
  for i, col in ipairs(term) do
    vim.g["terminal_color_" .. (i - 1)] = col
  end
end

return M
